-- Wave 9 step 1: make device location tenant-owned, and keep it as history.
--
-- ADR-004 declared `device_locations` as `deviceId @unique` with no tenant. Two consequences, both
-- of which this migration removes:
--
--   1. Every fix overwrote the last, so "where was this device when it went offline" could only ever
--      be answered with where it is now -- a confident wrong answer.
--   2. The row belonged to no tenant, so any read path keyed on device id would answer for a tenant
--      that does not own the device. With history enabled, that leak becomes every place the device
--      has ever been.
--
-- The unique index on deviceId is dropped rather than kept: it is what enforced one-row-per-device.
--
-- DDL beyond the tenantId handling is Prisma's own, generated by `migrate diff` against the live
-- database.

-- DropIndex
DROP INDEX "device_locations_deviceId_key";

-- Three steps, not one. Prisma's generated form adds `tenantId` as NOT NULL with no default, which
-- fails the moment the table holds a row -- so it only works on a database where nobody has ever
-- recorded a position. This database has none, but a tenant's production database might, and a
-- migration that only applies to an empty table is not a migration.
ALTER TABLE "device_locations" ADD COLUMN "tenantId" TEXT;

-- Backfilled from the owning device, which is the only place the ownership actually comes from.
UPDATE "device_locations" l
   SET "tenantId" = d."tenantId"
  FROM devices d
 WHERE d.id = l."deviceId"
   AND l."tenantId" IS NULL;

-- Any row still null means a location whose device no longer exists. Cascaded below, not left
-- ownerless: an ownerless location row is the exact hole this migration closes.
DELETE FROM "device_locations" WHERE "tenantId" IS NULL;

ALTER TABLE "device_locations"
  ALTER COLUMN "tenantId" SET NOT NULL,
  ADD COLUMN "recordedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ALTER COLUMN "updatedAt" DROP DEFAULT;

-- CreateIndex
CREATE INDEX "device_locations_tenantId_deviceId_recordedAt_idx" ON "device_locations"("tenantId", "deviceId", "recordedAt");

-- CreateIndex
CREATE INDEX "device_locations_tenantId_recordedAt_idx" ON "device_locations"("tenantId", "recordedAt");

-- CreateIndex
CREATE UNIQUE INDEX "device_locations_id_tenantId_key" ON "device_locations"("id", "tenantId");

-- AddForeignKey
ALTER TABLE "device_locations" ADD CONSTRAINT "device_locations_tenantId_fkey" FOREIGN KEY ("tenantId") REFERENCES "tenants"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- AddForeignKey
ALTER TABLE "device_locations" ADD CONSTRAINT "device_locations_deviceId_fkey" FOREIGN KEY ("deviceId") REFERENCES "devices"("id") ON DELETE CASCADE ON UPDATE CASCADE;
