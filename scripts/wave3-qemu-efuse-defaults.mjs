export const WAVE3_QEMU_EFUSE_DEFAULTS = {
  esp32: ESP32_EFUSE_HEX,
  esp32c3: ESP32C3_EFUSE_HEX,
};

export function wave3QemuEfuseBytes(target) {
  const hex = WAVE3_QEMU_EFUSE_DEFAULTS[target];
  if (!hex) throw new Error(`No Wave 3 QEMU eFuse default for target: ${target}`);
  return Buffer.from(hex, 'hex');
}
