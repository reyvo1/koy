/**
 * Wave 3 QEMU eFuse defaults — VERBATIM from ESP-IDF v5.5.5
 * tools/idf_py_actions/qemu_ext.py (QEMU_TARGETS default_efuse).
 *
 * The native `idf.py qemu` frontend always materialises build/qemu_efuse.bin
 * from these bytes and attaches it with
 *   -drive file=<efuse>,if=none,format=raw,id=efuse
 *   -global driver=nvram.<target>.efuse,property=drive,value=efuse
 * Omitting it leaves every emulated eFuse at 0, which is NOT the chip state
 * the ESP-IDF toolchain itself boots, so the repository-native runner must
 * reproduce it byte-for-byte.
 *
 * ESP32   : 124 bytes (chip revision 3)
 * ESP32-C3 : 1024 bytes (chip revision 0.3)
 */

